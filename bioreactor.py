"""
=================================================================
МОДЕЛИРОВАНИЕ CPS-БИОРЕАКТОРА
Лекция 9: Основы кибернетики
=================================================================

МОДЕЛЬ: Упрощённая кинетика роста дрожжей (уравнение Моно)
  - Глюкоза (S) расходуется на рост биомассы (X)
  - Помпа подаёт свежий субстрат (управляющее воздействие F_in)
  - Контроллер решает, сколько подавать субстрата
=================================================================
"""

import numpy as np
import matplotlib.pyplot as plt

# ============================================================
# БЛОК 1: ПАРАМЕТРЫ БИОРЕАКТОРА (ФИЗИЧЕСКИЙ МИР)
# ============================================================
# Эти параметры описывают сам биореактор
# Фиксированы для всех экспериментов.

MU_MAX = 0.4  # 1/ч  — максимальная скорость роста дрожжей
K_S = 0.5  # г/л  — константа полунасыщения (чем меньше, тем "жаднее" дрожжи к глюкозе)
Y_XS = 0.5  # г/г  — выход биомассы (сколько биомассы получается из 1 г глюкозы)
V = 1.0  # л    — объём реактора
S_IN = 20.0  # г/л  — концентрация глюкозы в подаваемом субстрате

# Целевое значение глюкозы (set point) — к чему стремится контроллер
SET_POINT = 5.0  # г/л

# Начальные условия в момент запуска эксперимента
X0 = 0.1  # г/л — начальная биомасса (мало дрожжей)
S0 = 2.0  # г/л — начальная глюкоза (меньше set point, чтобы контроллеру было что делать)

# ============================================================
# БЛОК 2: ПАРАМЕТРЫ СИМУЛЯЦИИ
# ============================================================
# Как долго и с каким шагом мы моделируем процесс.

T_END = 30  # часов — общая длительность эксперимента
DT = 0.05  # часов — шаг интегрирования (чем меньше, тем точнее, но медленнее)


# ============================================================
# БЛОК 3: ФУНКЦИЯ СИМУЛЯЦИИ
# ============================================================
def simulate(Kp=0.0, delay_hours=0.0, F_max=10.0):
    """
    Запуск симуляции биореактора.

    Параметры:
    ----------
    Kp : float
        Коэффициент усиления контроллера.
        Kp = 0   → открытый контур (контроллер выключен)
        Kp > 0   → замкнутый контур (контроллер работает)
        Kp большой → "агрессивный" контроллер (риск нестабильности)

    delay_hours : float
        Задержка в контуре обратной связи (часы).
        delay = 0   → контроллер видит текущее значение глюкозы
        delay > 0   → контроллер видит значение глюкозы delay часов назад

    F_max : float
        Максимальная мощность помпы (л/ч).
        Ограничение физического актуатора.

    Возвращает:
    -----------
    time_arr, X_arr, S_arr, F_arr : numpy arrays
        Массивы времени, биомассы, глюкозы и потока помпы.
    """

    # Вычисляем количество шагов симуляции
    n_steps = int(T_END / DT) + 1

    # Создаём массивы для хранения результатов
    time_arr = np.zeros(n_steps)
    X_arr = np.zeros(n_steps)
    S_arr = np.zeros(n_steps)
    F_arr = np.zeros(n_steps)

    # Начальные условия
    X = X0
    S = S0
    X_arr[0] = X
    S_arr[0] = S

    # Буфер для хранения истории измерений (нужен для моделирования задержки)
    delay_buffer = []
    delay_steps = int(delay_hours / DT)  # сколько шагов соответствует задержке

    # ===== ГЛАВНЫЙ ЦИКЛ СИМУЛЯЦИИ =====
    for i in range(n_steps - 1):
        t = i * DT
        time_arr[i] = t

        # -------------------------------------------------------
        # ШАГ 1: КОНТРОЛЛЕР принимает решение
        # -------------------------------------------------------

        # Определяем, какое значение глюкозы "видит" контроллер
        if delay_hours > 0:
            # Если есть задержка — добавляем текущее измерение в буфер
            delay_buffer.append(S)
            # Берём значение из прошлого (delay_steps шагов назад)
            if len(delay_buffer) > delay_steps:
                S_for_control = delay_buffer[-delay_steps - 1]
            else:
                # Пока буфер не заполнен — используем начальное значение
                S_for_control = S0
        else:
            # Без задержки — контроллер видит текущее значение
            S_for_control = S

        # Вычисляем ошибку: насколько текущее значение отличается от цели
        error = SET_POINT - S_for_control

        # Пропорциональный контроллер: F_in = Kp * error
        # Чем больше ошибка, тем сильнее подаём субстрат
        F_in = Kp * error

        # Ограничения помпы (физические пределы актуатора)
        F_in = max(0.0, F_in)  # помпа не может работать "в обратную сторону"
        F_in = min(F_in, F_max)  # помпа имеет максимальную мощность
        F_arr[i] = F_in

        # -------------------------------------------------------
        # ШАГ 2: ФИЗИЧЕСКИЙ ПРОЦЕСС (уравнение Моно + хемостат)
        # -------------------------------------------------------

        # Удельная скорость роста по уравнению Моно
        # mu = mu_max * S / (K_S + S)
        # При малом S: mu ≈ (mu_max/K_S) * S (линейный рост)
        # При большом S: mu ≈ mu_max (насыщение)
        mu = MU_MAX * S / (K_S + S)

        # Скорость разбавления (dilution rate) — как быстро обновляется среда
        D = F_in / V  # 1/ч

        # Уравнения хемостата (непрерывного биореактора):
        # dX/dt = mu*X - D*X
        #   (рост биомассы) - (вымывание с потоком)
        # dS/dt = D*(S_IN - S) - mu*X/Y_XS
        #   (подача глюкозы) - (потребление дрожжами)

        dX = (mu * X - D * X) * DT
        dS = (D * (S_IN - S) - mu * X / Y_XS) * DT

        # Обновляем состояние системы (метод Эйлера)
        X = X + dX
        S = S + dS

        # Защита от отрицательных значений (физический смысл)
        X = max(X, 0.0)
        S = max(S, 0.0)

        X_arr[i + 1] = X
        S_arr[i + 1] = S

    time_arr[-1] = T_END
    return time_arr, X_arr, S_arr, F_arr


# ============================================================
# БЛОК 4: НАСТРОЙКИ ЭКСПЕРИМЕНТОВ
# ============================================================
# !!! ИЗМЕНЕНИЕ ПАРАМЕТРОВ !!!
# Каждый эксперимент — это отдельный вызов функции simulate()
# с разными параметрами Kp и delay_hours.

print("=" * 60)
print("ЗАПУСК СИМУЛЯЦИИ")
print("=" * 60)

# -------------------------------------------------------
# ЭКСПЕРИМЕНТ 0: ОТКРЫТЫЙ КОНТУР (без управления)
# -------------------------------------------------------
# Контроллер ВЫКЛЮЧЕН (Kp = 0).
# Помпа не работает, глюкоза расходуется на рост дрожжей.
# Ожидаемый результат: глюкоза падает до нуля.

print("\n[Эксп. 0] Открытый контур (Kp = 0)")
t0, X0_arr, S0_arr, F0_arr = simulate(
    Kp=0.0,  # контроллер выключен
    delay_hours=0.0,  # задержка не важна (контроллер не работает)
    F_max=10.0  # максимальная мощность помпы
)

# -------------------------------------------------------
# ЭКСПЕРИМЕНТ 1: ГОМЕОСТАЗ (замкнутый контур)
# -------------------------------------------------------
# Контроллер ВКЛЮЧЕН с умеренным усилением.
# Система должна стабилизироваться на set point = 5.0 г/л.
# Ожидаемый результат: глюкоза плавно выходит на 5.0 и держится.

print("[Эксп. 1] Гомеостаз (Kp = 2.0)")
t1, X1_arr, S1_arr, F1_arr = simulate(
    Kp=2.0,  # умеренное усиление контроллера
    delay_hours=0.0,  # без задержки
    F_max=10.0
)

# -------------------------------------------------------
# ЭКСПЕРИМЕНТ 2: ЗАКОН ЭШБИ (переусиление)
# -------------------------------------------------------
# Контроллер слишком "агрессивный" (большой Kp).
# Система теряет стабильность, начинаются колебания.
# Ожидаемый результат: глюкоза колеблется вокруг set point.

print("[Эксп. 2] Закон Эшби (Kp = 20.0)")
t2, X2_arr, S2_arr, F2_arr = simulate(
    Kp=20.0,  # сильное усиление → нестабильность
    delay_hours=0.0,  # без задержки
    F_max=10.0
)

# -------------------------------------------------------
# ЭКСПЕРИМЕНТ 3: ПРОБЛЕМА ЗАДЕРЖКИ (Real-time CPS)
# -------------------------------------------------------
# Контроллер с правильным Kp, но с задержкой измерения.
# Контроллер "видит" глюкозу с опозданием.
# Ожидаемый результат: осцилляции из-за запаздывания реакции.

print("[Эксп. 3] Задержка (Kp = 2.0, delay = 1.0 ч)")
t3, X3_arr, S3_arr, F3_arr = simulate(
    Kp=2.0,  # то же усиление, что в Эксп. 1
    delay_hours=1.0,  # задержка 1 час
    F_max=10.0
)

print("\nСимуляция завершена!")
print("=" * 60)

# ============================================================
# БЛОК 5: ВИЗУАЛИЗАЦИЯ
# ============================================================

fig, axes = plt.subplots(2, 2, figsize=(14, 10))
fig.suptitle('CPS-БИОРЕАКТОР: Демонстрация принципов кибернетики',
             fontsize=16, fontweight='bold')

# --- График 1: Открытый контур ---
ax = axes[0, 0]
ax.plot(t0, S0_arr, 'b-', linewidth=2, label='Глюкоза (S)')
ax.axhline(SET_POINT, color='r', linestyle='--', linewidth=2,
           label=f'Set point = {SET_POINT} г/л')
ax.set_xlabel('Время, ч')
ax.set_ylabel('Концентрация, г/л')
ax.set_title('Эксп. 0: Открытый контур (без управления)\n' +
             'Глюкоза бесконтрольно падает', fontweight='bold')
ax.legend()
ax.grid(True, alpha=0.3)
ax.set_ylim(0, 15)

# --- График 2: Гомеостаз ---
ax = axes[0, 1]
ax.plot(t1, S1_arr, 'b-', linewidth=2, label='Глюкоза (S)')
ax.axhline(SET_POINT, color='r', linestyle='--', linewidth=2,
           label=f'Set point = {SET_POINT} г/л')
ax.set_xlabel('Время, ч')
ax.set_ylabel('Концентрация, г/л')
ax.set_title('Эксп. 1: Гомеостаз (замкнутый контур)\n' +
             'Система стабилизируется на set point', fontweight='bold')
ax.legend()
ax.grid(True, alpha=0.3)
ax.set_ylim(0, 15)

# --- График 3: Закон Эшби ---
ax = axes[1, 0]
ax.plot(t2, S2_arr, 'b-', linewidth=2, label='Глюкоза (S)')
ax.axhline(SET_POINT, color='r', linestyle='--', linewidth=2,
           label=f'Set point = {SET_POINT} г/л')
ax.set_xlabel('Время, ч')
ax.set_ylabel('Концентрация, г/л')
ax.set_title('Эксп. 2: Закон Эшби (Kp = 20.0)\n' +
             'Переусиление → нестабильность', fontweight='bold')
ax.legend()
ax.grid(True, alpha=0.3)
# Динамический ylim: чтобы осцилляции были видны
max_S2 = np.max(S2_arr)
ax.set_ylim(0, max(15, max_S2 * 1.2))

# --- График 4: Задержки ---
ax = axes[1, 1]
ax.plot(t3, S3_arr, 'b-', linewidth=2, label='Глюкоза (S)')
ax.axhline(SET_POINT, color='r', linestyle='--', linewidth=2,
           label=f'Set point = {SET_POINT} г/л')
ax.set_xlabel('Время, ч')
ax.set_ylabel('Концентрация, г/л')
ax.set_title('Эксп. 3: Задержка 1 час в контуре\n' +
             'Осцилляции из-за latency', fontweight='bold')
ax.legend()
ax.grid(True, alpha=0.3)
# Динамический ylim
max_S3 = np.max(S3_arr)
ax.set_ylim(0, max(15, max_S3 * 1.2))

plt.tight_layout()
plt.savefig('bioreactor_cps_simulation.png', dpi=150, bbox_inches='tight')
plt.show()

