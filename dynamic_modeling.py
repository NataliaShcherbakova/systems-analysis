# -*- coding: utf-8 -*-
"""
ПРАКТИКА 10: ДИНАМИЧЕСКОЕ МОДЕЛИРОВАНИЕ
Каскадная система: S → A → B* → C* с положительной обратной связью C* → A
1. Увидеть каскадную задержку в простой системе.
2. Понять, как найти стационарное состояние (равновесие).
3. Наглядно увидеть, как положительная обратная связь усиливает сигнал.
"""

import numpy as np
import matplotlib.pyplot as plt
from scipy.integrate import solve_ivp  # Решатель дифференциальных уравнений
from scipy.optimize import fsolve  # Решатель для поиска нуля функции (стационара)

# Настройки внешнего вида графиков
plt.rcParams['figure.figsize'] = (10, 5)
plt.rcParams['font.size'] = 12

# ============================================================================
# БЛОК 1: ПАРАМЕТРЫ СИСТЕМЫ
# ============================================================================
k1 = 0.05  # Скорость базовой активации A внешним сигналом S (очень слабая)
k2 = 0.5  # Скорость деградации (распада) A (сильная)
k3 = 0.5  # Скорость активации B компонентом A
k4 = 0.5  # Скорость деградации B
k5 = 0.5  # Скорость активации C компонентом B
k6 = 0.5  # Скорость деградации C

S = 1.0  # Сила постоянного внешнего сигнала (вход системы)
A_total = 3.0  # Общий запас (пул) компонента A.
B_total = 3.0  # Общий запас компонента B
C_total = 3.0  # Общий запас компонента C

y0 = [0.0, 0.0, 0.0]  # Начальные условия: в момент времени 0 все компоненты неактивны (0)
t_span = (0, 100)  # Интервал времени, который мы моделируем (от 0 до 100)
t_eval = np.linspace(0, 100, 500)  # 500 точек времени для построения гладкого графика

# ============================================================================
# БЛОК 2: УРАВНЕНИЯ (МАТЕМАТИЧЕСКАЯ МОДЕЛЬ)
# ============================================================================

def cascade(t, y):
    """
    Базовая система ОДУ без обратной связи.
    t - время
    y - список текущих концентраций [A, B, C]
    Возвращает: список скоростей изменения [dA/dt, dB/dt, dC/dt]
    """
    A, B, C = y

    # Закон действующих масс: Приток (активация) - Отток (деградация)
    # (A_total - A) означает, что активировать можно только неактивный остаток
    dA = k1 * S * (A_total - A) - k2 * A
    dB = k3 * A * (B_total - B) - k4 * B
    dC = k5 * B * (C_total - C) - k6 * C

    return [dA, dB, dC]


def cascade_feedback(t, y, k7):
    """
    Система с положительной обратной связью.
    k7 - сила обратной связи (насколько сильно C активирует A)
    """
    A, B, C = y

    # В уравнение для dA добавлено слагаемое: + k7 * C * (A_total - A)
    # Это значит: чем больше накопилось C, тем быстрее активируется A.
    dA = k1 * S * (A_total - A) + k7 * C * (A_total - A) - k2 * A
    dB = k3 * A * (B_total - B) - k4 * B
    dC = k5 * B * (C_total - C) - k6 * C

    return [dA, dB, dC]


# ============================================================================
# ЗАДАНИЕ 1: Базовая динамика (без обратной связи)
# ============================================================================
# Решаем систему уравнений и сохраняем результат в переменную sol
sol_base = solve_ivp(cascade, t_span, y0, t_eval=t_eval, rtol=1e-8)

plt.figure()
plt.plot(sol_base.t, sol_base.y[0], 'b-', lw=2, label='A (активатор)')
plt.plot(sol_base.t, sol_base.y[1], 'g-', lw=2, label='B* (посредник)')
plt.plot(sol_base.t, sol_base.y[2], 'r-', lw=2, label='C* (исполнитель)')
plt.title('Задание 1: Базовая динамика (система "спит", сигнал слабый)')
plt.xlabel('Время')
plt.ylabel('Концентрация')
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.savefig('task1_base_dynamics.png', dpi=150)
plt.show()  # все кривые остаются низкими.

# ============================================================================
# ЗАДАНИЕ 2: Поиск стационарного состояния (равновесия)
# ============================================================================
# Стационар - это когда концентрации перестают меняться (dA/dt = 0, dB/dt = 0, dC/dt = 0)
# Функция fsolve ищет такие значения y, при которых функция cascade возвращает [0, 0, 0]

def steady_state_eq(y):
    return cascade(0, y)  # Передаем 0 вместо времени, так как в стационаре время не важно

# Начинаем поиск с последних значений нашего решения (они уже близки к равновесию)
y_steady = fsolve(steady_state_eq, sol_base.y[:, -1])

print("=" * 60)
print("ЗАДАНИЕ 2: Стационарные концентрации (БЕЗ обратной связи)")
print("=" * 60)
print(f"  A  = {y_steady[0]:.3f} (из {A_total})")
print(f"  B* = {y_steady[1]:.3f} (из {B_total})")
print(f"  C* = {y_steady[2]:.3f} (из {C_total})")
print("Вывод: Без обратной связи система выходит на очень низкий уровень.\n")

# ============================================================================
# ЗАДАНИЕ 3: Влияние положительной обратной связи (параметр k7)
# ============================================================================
# Мы проверим, как меняется выход системы (C*) при разной силе обратной связи.

k7_values = [0.0, 1.0, 3.0]  # 0.0 = без связи, 3.0 = сильная связь
colors = ['gray', 'orange', 'red']

plt.figure(figsize=(10, 5))

print("=" * 60)
print("ЗАДАНИЕ 3: Влияние силы обратной связи (k7) на выход C*")
print("=" * 60)

for k7, color in zip(k7_values, colors):
    # Решаем систему с текущим значением k7
    sol_fb = solve_ivp(lambda t, y: cascade_feedback(t, y, k7),
                       t_span, y0, t_eval=t_eval, rtol=1e-8)

    # Находим новый стационар для этого k7
    y_ss_fb = fsolve(lambda y: cascade_feedback(0, y, k7), sol_fb.y[:, -1])
    c_final = y_ss_fb[2]

    # Считаем, во сколько раз вырос выход по сравнению с базовым (k7=0)
    gain = (c_final / y_steady[2])

    print(f"При k7 = {k7:<4} | Финальный C* = {c_final:<5.2f} | Усиление: {gain:.1f}x")

    # Рисуем кривую C*(t) для этого k7
    plt.plot(sol_fb.t, sol_fb.y[2], color=color, lw=2.5,
             label=f'k7 = {k7} (C* = {c_final:.2f})')

plt.title('Задание 3: Как положительная обратная связь (k7) усиливает выход C*')
plt.xlabel('Время')
plt.ylabel('Концентрация C* (исполнитель)')
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.savefig('task3_feedback_comparison.png', dpi=150)
plt.show()
