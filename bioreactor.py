print("\n" + "=" * 60)
print("РЕЗУЛЬТАТЫ СИМУЛЯЦИИ:")
print("=" * 60)
print(f"Эксп. 0 (Open-loop):   S финальная = {S0_arr[-1]:.2f} г/л")
print(f"Эксп. 1 (Гомеостаз):   S финальная = {S1_arr[-1]:.2f} г/л [OK]")
print(f"Эксп. 2 (Эшби):        S амплитуда колебаний = {np.max(S2_arr) - np.min(S2_arr):.2f} г/л [WARN]")
print(f"Эксп. 3 (Задержка):    S амплитуда колебаний = {np.max(S3_arr[-50:]) - np.min(S3_arr[-50:]):.2f} г/л [WARN]")
