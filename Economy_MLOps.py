# ============================================================================
# БЛОК 1. ОПРЕДЕЛЕНИЕ СТРУКТУРЫ ПАРАМЕТРОВ МОДЕЛИ
# ============================================================================
# Используем dataclass для чистой структуры данных.
# Каждый параметр имеет чёткий экономический смысл и единицы измерения.

@dataclass
class PipelineParams:
    """
    Параметрическая модель биоинформатического пайплайна.
    Все денежные значения — в рублях (руб.), временные — в часах (ч).
    """

    # --- ОБЪЁМНЫЕ ПАРАМЕТРЫ (масштаб нагрузки) ---
    samples_per_year: int
    # Количество образцов (пациентов/проб), обрабатываемых системой за 1 год.
    # Единицы: [образцов / год]
    # Источник оценки: данные лаборатории или плановые показатели.
    # В нашем кейсе: 100 образцов/мес × 12 = 1200 образцов/год.

    bioinformatician_hourly_rate: float
    # Полная стоимость 1 часа работы биоинформатика (с учётом налогов,
    # страховых взносов и накладных расходов организации).
    # Единицы: [руб. / час]
    # Источник оценки: данные HR-отдела или средние по рынку (hh.ru).
    # Важно: используется и для расчёта CAPEX (разработка), и OPEX (поддержка).

    # --- ПАРАМЕТРЫ СОСТОЯНИЯ "AS IS" (текущий ручной процесс) ---
    time_per_sample_as_is: float
    # Трудозатраты биоинформатика на обработку ОДНОГО образца в ручном режиме.
    # Включает: запуск скриптов, мониторинг, разбор логов, сборку отчёта.
    # Единицы: [часов / образец]
    # Источник оценки: хронометраж работы или экспертная оценка.

    compute_cost_per_sample_as_is: float
    # Стоимость вычислительных ресурсов (облако/сервер) на 1 образец
    # в неоптимизированном режиме. Включает потери из-за перезапусков
    # при ошибках окружения и неэффективном использовании RAM/CPU.
    # Единицы: [руб. / образец]
    # Источник оценки: тарифы облачного провайдера (Yandex Cloud, AWS).

    storage_cost_per_sample_as_is: float
    # Стоимость хранения данных 1 образца в течение 1 года
    # при хаотичном подходе (дублирование файлов, отсутствие архивации).
    # Единицы: [руб. / образец / год]
    # Источник оценки: тарифы S3-хранилища (стандарт "Standard").

    # --- ПАРАМЕТРЫ СОСТОЯНИЯ "TO BE" (автоматизированный MLOps-пайплайн) ---
    time_per_sample_to_be: float
    # Трудозатраты биоинформатика на 1 образец ПОСЛЕ автоматизации.
    # Включает только: валидацию алертов, разбор исключительных случаев,
    # финальную проверку отчёта. Рутина исключена.
    # Единицы: [часов / образец]

    compute_cost_per_sample_to_be: float
    # Стоимость вычислений на 1 образец в оптимизированном режиме
    # (контейнеризация через Docker, автоскейлинг, отсутствие перезапусков).
    # Единицы: [руб. / образец]

    storage_cost_per_sample_to_be: float
    # Стоимость хранения 1 образца в год при структурированном подходе
    # (S3 + архивация старых версий через DVC, lifecycle policies).
    # Единицы: [руб. / образец / год]

    # --- CAPEX: ЕДИНОВРЕМЕННЫЕ КАПИТАЛЬНЫЕ ЗАТРАТЫ ---
    dev_hours: float
    # Количество человеко-часов, необходимых для разработки и настройки
    # автоматизированного пайплайна (написание Dockerfile, GitHub Actions,
    # интеграция DVC, MLflow, написание тестов).
    # Единицы: [часов]
    # Источник оценки: экспертная оценка техлида или аналогичные проекты.

    initial_infrastructure_cost: float
    # Первоначальные затраты на настройку облачной инфраструктуры,
    # покупку лицензий, развёртывание Kubernetes-кластера и т.д.
    # Единицы: [руб.]
    # Это фиксированная сумма, не зависящая от объёма образцов.

    # --- OPEX: ЕЖЕГОДНЫЕ ФИКСИРОВАННЫЕ ОПЕРАЦИОННЫЕ ЗАТРАТЫ ---
    annual_mlops_subscription: float
    # Годовая стоимость подписок на MLOps-сервисы:
    # MLflow (или managed-версия), мониторинг (Prometheus/Grafana),
    # системы алертинга, резервного копирования.
    # Единицы: [руб. / год]

    annual_infrastructure_support: float
    # Годовая стоимость базовой поддержки инфраструктуры:
    # зарплата DevOps-инженера (доля времени), техподдержка облака,
    # обновления безопасности.
    # Единицы: [руб. / год]


# ============================================================================
# БЛОК 2. ИСХОДНЫЕ ДАННЫЕ ИЗ КЕЙСА "ГЕНОМНАЯ ЛАБОРАТОРИЯ"
# ============================================================================
# Все значения основаны на реалистичных оценках для небольшой
# исследовательской лаборатории, обрабатывающей WGS-данные.

params = PipelineParams(
    samples_per_year=1200,  # 100 образцов/мес × 12 мес = 1200 образцов/год
    bioinformatician_hourly_rate=1500.0,  # Полная стоимость часа специалиста (руб./час)

    # === СОСТОЯНИЕ "AS IS" (ручной режим) ===
    time_per_sample_as_is=4.0,  # 4 часа ручного труда на 1 образец
    compute_cost_per_sample_as_is=150.0,  # 150 руб. на вычисления (неоптимизировано)
    storage_cost_per_sample_as_is=50.0,  # 50 руб./год на хранение (хаотично)

    # === СОСТОЯНИЕ "TO BE" (MLOps-пайплайн) ===
    time_per_sample_to_be=0.5,  # 0.5 часа — только валидация и исключения
    compute_cost_per_sample_to_be=80.0,  # 80 руб. — оптимизированные контейнеры
    storage_cost_per_sample_to_be=30.0,  # 30 руб./год — S3 + архивация через DVC

    # === CAPEX (единовременно, в 1-м году) ===
    dev_hours=250.0,  # 250 часов на разработку пайплайна
    initial_infrastructure_cost=100000.0,  # 100 тыс. руб. на первичную настройку

    # === OPEX (ежегодно, годы 1–3) ===
    annual_mlops_subscription=120000.0,  # 120 тыс. руб./год на подписки MLOps
    annual_infrastructure_support=60000.0  # 60 тыс. руб./год на поддержку
)


# ============================================================================
# БЛОК 3. ФУНКЦИЯ РАСЧЁТА ЭКОНОМИЧЕСКИХ ПОКАЗАТЕЛЕЙ
# ============================================================================

def calculate_economics(p: PipelineParams, years: int = 3) -> dict:
    """
    Рассчитывает TCO, ROI и срок окупаемости для заданного горизонта планирования.

    Args:
        p: параметры пайплайна (объём, стоимости, трудозатраты)
        years: горизонт планирования в годах (стандартно 3–5 лет)

    Returns:
        dict со всеми ключевыми экономическими метриками
    """

    # -------------------------------------------------------------------------
    # РАСЧЁТ ЗАТРАТ ДЛЯ СОСТОЯНИЯ "AS IS" (старый ручной процесс)
    # -------------------------------------------------------------------------

    # Ежегодные затраты на труд биоинформатиков в ручном режиме
    # = (количество образцов) × (часов на образец) × (стоимость часа)
    labor_cost_as_is_annual = (
            p.samples_per_year
            * p.time_per_sample_as_is
            * p.bioinformatician_hourly_rate
    )

    # Ежегодные затраты на вычисления в неоптимизированном режиме
    # = (количество образцов) × (стоимость вычислений на образец)
    compute_cost_as_is_annual = (
            p.samples_per_year
            * p.compute_cost_per_sample_as_is
    )

    # Ежегодные затраты на хранение данных (хаотичное, с дублированием)
    # = (количество образцов) × (стоимость хранения образца в год)
    storage_cost_as_is_annual = (
            p.samples_per_year
            * p.storage_cost_per_sample_as_is
    )

    # Суммарные ежегодные затраты в состоянии "As Is"
    # Это та сумма, которую лаборатория ТРАТИТ каждый год без автоматизации
    total_cost_as_is_annual = (
            labor_cost_as_is_annual
            + compute_cost_as_is_annual
            + storage_cost_as_is_annual
    )

    # -------------------------------------------------------------------------
    # РАСЧЁТ CAPEX (единовременные капитальные затраты)
    # -------------------------------------------------------------------------

    # CAPEX = затраты на разработку + затраты на первичную инфраструктуру
    # Это инвестиция, которая делается ОДИН РАЗ в начале проекта
    capex = (
            p.dev_hours * p.bioinformatician_hourly_rate  # стоимость разработки
            + p.initial_infrastructure_cost  # настройка инфраструктуры
    )

    # -------------------------------------------------------------------------
    # РАСЧЁТ OPEX (ежегодные операционные затраты для "To Be")
    # -------------------------------------------------------------------------

    # Труд биоинформатика после автоматизации (значительно сокращён)
    labor_cost_to_be_annual = (
            p.samples_per_year
            * p.time_per_sample_to_be
            * p.bioinformatician_hourly_rate
    )

    # Вычисления в оптимизированном режиме (Docker, автоскейлинг)
    compute_cost_to_be_annual = (
            p.samples_per_year
            * p.compute_cost_per_sample_to_be
    )

    # Хранение данных в структурированном виде (S3 + DVC-архивация)
    storage_cost_to_be_annual = (
            p.samples_per_year
            * p.storage_cost_per_sample_to_be
    )

    # Фиксированные ежегодные затраты на MLOps-инфраструктуру
    # (не зависят от количества образцов — это "налог" на автоматизацию)
    fixed_opex_annual = (
            p.annual_mlops_subscription
            + p.annual_infrastructure_support
    )

    # Суммарный ежегодный OPEX после внедрения MLOps
    total_opex_annual = (
            labor_cost_to_be_annual
            + compute_cost_to_be_annual
            + storage_cost_to_be_annual
            + fixed_opex_annual
    )

    # -------------------------------------------------------------------------
    # ИТОГОВЫЕ ЭКОНОМИЧЕСКИЕ МЕТРИКИ
    # -------------------------------------------------------------------------

    # TCO (Total Cost of Ownership) — совокупная стоимость владения
    # за весь горизонт планирования (CAPEX + OPEX × число лет)
    # Формула: TCO = CAPEX + Σ(OPEX_t) для t от 1 до n
    tco = capex + (total_opex_annual * years)

    # Затраты на старый процесс за тот же горизонт (для сравнения)
    # Это "альтернативная стоимость" — сколько мы бы потратили,
    # если бы НЕ внедряли автоматизацию
    cost_as_is_total = total_cost_as_is_annual * years

    # GAIN (выгода) — чистая экономия за счёт автоматизации
    # = (затраты As Is) - (затраты To Be)
    # Если Gain > 0, то автоматизация экономически оправдана
    gain = cost_as_is_total - tco

    # ROI (Return on Investment) — возврат на инвестиции в процентах
    # Показывает, сколько рублей выгоды приносит каждый вложенный рубль
    # Формула: ROI = (Gain / Cost) × 100%
    roi = (gain / tco) * 100 if tco > 0 else 0

    # Ежегодная экономия — разница в ежегодных затратах
    # Используется для расчёта срока окупаемости
    annual_savings = total_cost_as_is_annual - total_opex_annual

    # PAYBACK PERIOD (срок окупаемости) в месяцах
    # = CAPEX / (ежегодная экономия / 12)
    # Показывает, через сколько месяцев инвестиции "вернутся"
    payback_months = (capex / annual_savings) * 12 if annual_savings > 0 else float('inf')

    # Высвобожденные человеко-часы биоинформатика в год
    # Это НЕМATERIALНАЯ выгода: время можно направить на R&D,
    # научные публикации, разработку новых моделей
    freed_hours_per_year = (
            (p.time_per_sample_as_is - p.time_per_sample_to_be)
            * p.samples_per_year
    )

    return {
        "CAPEX (руб.)": round(capex, 2),
        "OPEX в год (руб.)": round(total_opex_annual, 2),
        f"TCO за {years} года (руб.)": round(tco, 2),
        "Затраты As Is за 3 года (руб.)": round(cost_as_is_total, 2),
        "Чистая экономия (Gain) за 3 года (руб.)": round(gain, 2),
        "ROI (%)": round(roi, 1),
        "Срок окупаемости (мес.)": round(payback_months, 1),
        "Высвобождено часов биоинформатика в год": round(freed_hours_per_year, 1)
    }


# ============================================================================
# БЛОК 4. ВЫПОЛНЕНИЕ РАСЧЁТА И ВЫВОД РЕЗУЛЬТАТОВ
# ============================================================================

results = calculate_economics(params, years=3)

print("📊 РЕЗУЛЬТАТЫ ЭКОНОМИЧЕСКОГО ОБОСНОВАНИЯ (Горизонт: 3 года)")
